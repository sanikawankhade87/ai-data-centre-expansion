def front_page() -> None:
    tiles = "".join(
        f'<div class="tile">{svg_img(icon, "")}'
        f'<div class="n">Tab {n}</div>'
        f'<div class="t">{label.split("· ", 1)[1]}</div>'
        f'<div class="d">{question}</div>'
        f'<div class="go">Open Tab {n} below ↓</div></div>'
        for n, (label, _, icon, question) in enumerate(TABS, start=1)
    )
    st.html(STYLE + f"""
<section class="hero">
  <div>
    <div class="eyebrow">Data narrative · Energy and AI</div>
    <h1>AI Data Centre Expansion</h1>
    <p class="q">{QUESTION}</p>
    <div class="who">
      <span class="avatar">DR</span>
      <span>Our app is for <b>{PERSONA_NAME}</b>, {PERSONA}</span>
    </div>
  </div>
  <div class="art">{svg_img("hero.svg", "Illustration of a data-centre campus powered by the grid")}</div>
</section>
<div class="answer"><b>🧭 The answer the data supports:</b> {ANSWER}</div>
<div class="tiles">{tiles}</div>
""")
    st.caption("Tabs 1 to 3 show the supply side of the expansion. "
               "Tab 4 compares it with measured AI use and carries the answer. "
               "Choose a tab below to explore.")


front_page()

for tab, (label, module_name, _, _) in zip(st.tabs([t[0] for t in TABS]), TABS):
    with tab:
        try:
            module = importlib.import_module(module_name)
        except ModuleNotFoundError as err:
            if err.name != module_name:
                raise  # a package the tab needs is missing: show the real error
            st.info(f"`{module_name}.py` has not been added to the repository yet.")
            continue
        module.render()
